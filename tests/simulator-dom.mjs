import {JSDOM} from 'jsdom';
import assert from 'node:assert/strict';
import {renderSimulator,renderSimulatorAdmin} from '../simulator.js';
const dom=new JSDOM('<div id="root"></div>',{url:'https://corretores.astrion360.com.br'});
globalThis.document=dom.window.document;
globalThis.window=dom.window;
const root=document.querySelector('#root');
const product={id:'auto',name:'Automóveis',category:'Automóveis',active:true};
const plan={id:'plan',product_id:'auto',name:'Plano normal',group_code:null,reference_credit_amount:71200,term_months:89,admin_fee_pct:18.31,reserve_fund_pct:2,other_total_pct:0,insurance_monthly_amount:0,prestamista_rate_monthly:.0007,annual_adjustment_pct:0,source_label:'Premissa de referência Astrion',active:true,approved_for_use:true};
const ctx={products:[product],plans:[plan],segments:[{code:'auto',product_category:'Automóveis',credit_min:10000,credit_max:500000,max_term_months:100}],groups:[],opps:[],clients:[],prefill:null,isAdmin:false,toast:()=>{}};
renderSimulator(root,ctx);
const credit=root.querySelector('#sim-credit');
assert.ok(credit);
assert.equal(credit.value,'71200');
assert.equal(root.querySelector('#sim-interest').value,'1.97');
assert.equal(root.querySelector('#sim-admin-fee').value,'18.31');
assert.equal(root.querySelector('#sim-reserve-fee').value,'2');
credit.value='100000';credit.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/70,00/);
assert.equal(root.querySelector('#sim-print').disabled,false);
const interest=root.querySelector('#sim-interest');
interest.value='2.12';interest.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/Financiamento/);
assert.match(root.querySelector('#sim-finance-linked').textContent,/100.000/);
assert.match(root.querySelector('#sim-finance-linked').textContent,/89 meses/);
// TA e FR editáveis apenas na simulação.
const fee=root.querySelector('#sim-admin-fee');fee.value='20';fee.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/20%/);
const reserve=root.querySelector('#sim-reserve-fee');reserve.value='3';reserve.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/3%/);
// Parcela reduzida após seleção do mês hipotético.
const mode=root.querySelector('#sim-payment-mode');
mode.value='half';mode.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(root.querySelector('#sim-contemplation').disabled,false);
assert.match(root.querySelector('#sim-results').textContent,/50%/);
const month=root.querySelector('#sim-contemplation');
month.value='40';month.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/mês 40/);
assert.equal(root.querySelector('#sim-print').disabled,false);
assert.ok(!root.querySelector('#sim-reduced-info').classList.contains('hidden'));
const admin={...ctx,isAdmin:true,navigate:()=>{},sb:{},reload:async()=>{}};
renderSimulatorAdmin(root,admin);
assert.ok(root.querySelector('#sim-admin-form'));
assert.ok(root.querySelector('#adm-product'));
assert.equal(root.querySelector('#adm-prestamista').getAttribute('step'),'0.00001');
assert.ok(root.querySelector('#adm-reference'));
// Referência de Serviços: prazo informado de 39m, contra limite anterior do catálogo de 36m.
const service={id:'service',name:'Serviços',category:'Serviços',active:true};
const servicePlan={...plan,id:'service-plan',product_id:'service',term_months:39,reference_credit_amount:15600,admin_fee_pct:24.56,reserve_fund_pct:5,prestamista_rate_monthly:.0007};
const referenceCtx={...ctx,products:[service],plans:[servicePlan],segments:[{code:'services',product_category:'Serviços',credit_min:8000,credit_max:16000,max_term_months:36}]};
renderSimulator(root,referenceCtx);
assert.equal(root.querySelector('#sim-credit').value,'15600');
assert.equal(root.querySelector('#sim-print').disabled,false);
assert.match(root.querySelector('#sim-results').textContent,/excede a referência antiga/);
assert.equal(root.querySelector('#sim-interest').value,'5.9');
console.log('Órbita Simula DOM smoke tests: OK');
