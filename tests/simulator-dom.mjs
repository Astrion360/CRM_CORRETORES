import {JSDOM} from 'jsdom';
import assert from 'node:assert/strict';
import {renderSimulator,renderSimulatorAdmin} from '../simulator.js';
const dom=new JSDOM('<div id="root"></div>',{url:'https://corretores.astrion360.com.br'});
globalThis.document=dom.window.document;
globalThis.window=dom.window;
const root=document.querySelector('#root');
const product={id:'auto',name:'Automóveis',category:'Automóveis',active:true};
const plan={id:'plan',product_id:'auto',name:'Plano normal',group_code:null,term_months:100,admin_fee_pct:15,reserve_fund_pct:2,other_total_pct:0,insurance_monthly_amount:0,annual_adjustment_pct:0,source_label:'Tabela aprovada 20/10/2026',active:true,approved_for_use:true};
