renderSimulator(root,ctx);
const credit=root.querySelector('#sim-credit');
assert.ok(credit);
credit.value='100000';credit.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/117.000/);
assert.equal(root.querySelector('#sim-print').disabled,false);
const interest=root.querySelector('#sim-interest');
interest.value='12';interest.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.match(root.querySelector('#sim-results').textContent,/Financiamento/);
const admin={...ctx,isAdmin:true,navigate:()=>{},sb:{},reload:async()=>{}};
renderSimulatorAdmin(root,admin);
assert.ok(root.querySelector('#sim-admin-form'));
assert.ok(root.querySelector('#adm-product'));
console.log('Órbita Simula DOM smoke tests: OK');
